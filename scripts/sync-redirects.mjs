#!/usr/bin/env node
/**
 * Generate public/_redirects for Cloudflare Workers static assets.
 * Keep PATH_REDIRECTS / IMAGE_REDIRECTS in functions/_middleware.js in sync.
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MIDDLEWARE = path.join(ROOT, 'functions', '_middleware.js');
const OUT = path.join(ROOT, 'public', '_redirects');

const IMAGE_STEMS = {
	'rust-hacks-hero': 'arc-raiders-hero',
	'rust-esp-overlay': 'arc-raiders-esp-overlay',
	'rust-esp-bots': 'arc-raiders-wallhack',
	'rust-esp-hitbox': 'arc-raiders-aimbot',
	'rust-aimbot-menu': 'arc-raiders-menu',
	'rust-recoil-trainer': 'arc-raiders-combat',
	'rust-aimbot-ui': 'arc-raiders-aimbot-ui',
	'rust-wallhack-ui': 'arc-raiders-wallhack-ui',
	'rust-soft-aim-ui': 'arc-raiders-soft-aim-ui',
	'rust-radar-ui': 'arc-raiders-radar-ui',
	'rust-cheats-menu': 'arc-raiders-cheats-menu',
	'rust-hacks-cover': 'arc-raiders-cover',
	'rust-hacks-panel': 'arc-raiders-panel',
	'rust-hacks-status': 'arc-raiders-status',
};

const VARIANT_WIDTHS = {
	'rust-hacks-hero': [480, 640, 960, 1400],
	'rust-esp-overlay': [480, 640, 960, 1400],
	'rust-esp-bots': [480, 640, 960, 1400],
	'rust-esp-hitbox': [480, 640, 960, 1400],
	'rust-aimbot-menu': [480, 640, 960, 1400],
	'rust-recoil-trainer': [480, 640, 960, 1400],
	'rust-aimbot-ui': [480, 960],
	'rust-wallhack-ui': [480, 960],
	'rust-soft-aim-ui': [480, 960],
	'rust-radar-ui': [480, 960],
	'rust-cheats-menu': [480, 960],
	'rust-hacks-cover': [480, 960],
	'rust-hacks-panel': [480, 960],
	'rust-hacks-status': [480, 960],
};

function parseObjectBlock(source, name) {
	const match = source.match(new RegExp(`const ${name} = \\{([\\s\\S]*?)\\n\\};`));
	if (!match) throw new Error(`Could not parse ${name} from middleware`);
	const entries = [];
	for (const line of match[1].split('\n')) {
		const m = line.match(/^\s*'([^']+)':\s*'([^']+)',?\s*(?:\/\/.*)?$/);
		if (m) entries.push([m[1], m[2]]);
	}
	return entries;
}

function line(from, to) {
	return `${from} ${to} 301`;
}

const middleware = await readFile(MIDDLEWARE, 'utf8');
const pathRedirects = parseObjectBlock(middleware, 'PATH_REDIRECTS');
const imageRedirects = parseObjectBlock(middleware, 'IMAGE_REDIRECTS');

const lines = [
	'# Auto-generated by scripts/sync-redirects.mjs — do not edit by hand.',
	'# Cloudflare Workers static assets reads this file from dist/_redirects.',
	'# Host-level redirects (www, legacy domains) stay in functions/_middleware.js.',
	'',
	'# Path redirects',
	...pathRedirects.map(([from, to]) => line(from, to)),
	'',
	'# Legacy image/video URLs → arc-raiders canonical assets',
	...imageRedirects.map(([from, to]) => line(from, to)),
];

for (const [oldStem, newStem] of Object.entries(IMAGE_STEMS)) {
	for (const width of VARIANT_WIDTHS[oldStem] ?? []) {
		lines.push(line(`/images/${oldStem}-${width}w.webp`, `/images/${newStem}-${width}w.webp`));
	}
}

await writeFile(OUT, `${lines.join('\n')}\n`);
console.log(`Wrote ${OUT} (${lines.length} lines)`);
